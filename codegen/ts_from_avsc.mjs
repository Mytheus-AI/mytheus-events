// AUTO-GENERATING script: emits TypeScript interfaces from the Avro schemas.
// One file per topic into clients/typescript/src/ plus envelope.ts and index.ts.
// Generated output is deterministic; do not hand-edit.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS = join(ROOT, "schemas");
const OUT = join(ROOT, "clients", "typescript", "src");
const HEADER = "// AUTO-GENERATED by codegen/ts_from_avsc.mjs. Do not edit.\n";

const TOPICS = readdirSync(SCHEMAS)
  .filter((d) => !d.startsWith("_") && statSync(join(SCHEMAS, d)).isDirectory())
  .sort();

const readAvsc = (p) => JSON.parse(readFileSync(p, "utf8"));
const camel = (topic) =>
  topic.split("-").map((s, i) => (i === 0 ? s : s[0].toUpperCase() + s.slice(1))).join("");

function tsType(t) {
  if (Array.isArray(t)) {
    const branches = t.filter((b) => b !== "null").map(tsType);
    const base = branches.length ? branches.join(" | ") : "null";
    return t.includes("null") ? `${base} | null` : base;
  }
  if (typeof t === "object") {
    if (t.type === "enum") return t.symbols.map((s) => JSON.stringify(s)).join(" | ");
    if (t.type === "array") return `${tsType(t.items)}[]`;
    const logical = t.logicalType;
    if (logical === "uuid") return "string";
    if (logical === "timestamp-micros" || logical === "date") return "number";
    return tsType(t.type);
  }
  const prim = { string: "string", int: "number", long: "number", float: "number", double: "number", boolean: "boolean" };
  if (prim[t]) return prim[t];
  if (String(t).endsWith("EventEnvelopeHeader")) return "EventEnvelopeHeader";
  return "string";
}

function iface(name, fields, importHeader) {
  const lines = [HEADER, ""];
  if (importHeader) lines.push('import type { EventEnvelopeHeader } from "./envelope";', "");
  lines.push(`export interface ${name} {`);
  for (const f of fields) {
    const optional = Array.isArray(f.type) && f.type.includes("null") ? "?" : "";
    lines.push(`  ${f.name}${optional}: ${tsType(f.type)};`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

function main() {
  mkdirSync(OUT, { recursive: true });

  const env = readAvsc(join(SCHEMAS, "_envelope", "EventEnvelopeHeader.avsc"));
  const dlq = readAvsc(join(ROOT, "contracts", "DlqEnvelope.avsc"));
  let envSrc = iface("EventEnvelopeHeader", env.fields, false);
  envSrc += "\n" + iface("DlqEnvelope", dlq.fields, false).replace(HEADER, "");
  writeFileSync(join(OUT, "envelope.ts"), envSrc);

  const exports = ['export type { EventEnvelopeHeader, DlqEnvelope } from "./envelope";'];
  for (const topic of TOPICS) {
    const raw = readAvsc(join(SCHEMAS, topic, "v1.avsc"));
    writeFileSync(join(OUT, `${camel(topic)}.ts`), iface(raw.name, raw.fields, true));
    exports.push(`export type { ${raw.name} } from "./${camel(topic)}";`);
  }
  writeFileSync(join(OUT, "index.ts"), HEADER + "\n" + exports.join("\n") + "\n");

  console.log(`generated TypeScript client: ${TOPICS.length} topic interfaces + envelope.ts in ${OUT}`);
}

main();
