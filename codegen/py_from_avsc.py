"""Generate Python (pydantic v2) client models from the Avro schemas.

Emits one module per topic into clients/python/mytheus_events/ plus envelope.py
(EventEnvelopeHeader + DlqEnvelope) and an __init__.py that re-exports every model.
Generated output is deterministic; do not hand-edit. Usage:

    python codegen/py_from_avsc.py [schemas_dir_ignored] [out_dir]
"""
from __future__ import annotations

import os
import sys

from _schemas import DLQ_PATH, ENVELOPE_PATH, ROOT, TOPICS, load_raw, topic_schema_path

DEFAULT_OUT = os.path.join(ROOT, "clients", "python", "mytheus_events")

HEADER = "# AUTO-GENERATED by codegen/py_from_avsc.py. Do not edit.\n"


def _snake(topic: str) -> str:
    return topic.replace("-", "_")


def py_type(t) -> str:
    """Map an Avro type node to a Python type annotation string."""
    if isinstance(t, list):  # union
        non_null = [b for b in t if b != "null"]
        inner = py_type(non_null[0]) if non_null else "None"
        return f"Optional[{inner}]" if "null" in t else inner
    if isinstance(t, dict):
        kind, logical = t.get("type"), t.get("logicalType")
        if kind == "enum":
            return "Literal[" + ", ".join(repr(s) for s in t["symbols"]) + "]"
        if kind == "array":
            return f"List[{py_type(t['items'])}]"
        if logical in ("uuid",):
            return "str"
        if logical in ("timestamp-micros", "date"):
            return "int"
        return py_type(kind)
    # primitive or named reference
    return {
        "string": "str", "int": "int", "long": "int",
        "float": "float", "double": "float", "boolean": "bool",
    }.get(t, "EventEnvelopeHeader" if t.endswith("EventEnvelopeHeader") else "str")


def _field_line(field: dict) -> str:
    name, t = field["name"], field["type"]
    ann = py_type(t)
    has_default = "default" in field
    if has_default:
        default = field["default"]
        return f"    {name}: {ann} = {default!r}"
    # nullable without explicit default still defaults to None for ergonomics
    if isinstance(t, list) and "null" in t:
        return f"    {name}: {ann} = None"
    return f"    {name}: {ann}"


def _model(name: str, fields: list[dict], *, with_header_import: bool) -> str:
    lines = [f"class {name}(BaseModel):"]
    body = [_field_line(f) for f in fields]
    lines.extend(body if body else ["    pass"])
    return "\n".join(lines) + "\n"


def _module_preamble(needs_header: bool) -> str:
    imports = [
        HEADER,
        "from __future__ import annotations\n",
        "from typing import List, Literal, Optional\n",
        "\n",
        "from pydantic import BaseModel\n",
    ]
    if needs_header:
        imports.append("\nfrom .envelope import EventEnvelopeHeader\n")
    return "".join(imports) + "\n\n"


def main() -> None:
    out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    os.makedirs(out, exist_ok=True)

    # envelope.py -> EventEnvelopeHeader + DlqEnvelope
    env = load_raw(ENVELOPE_PATH)
    dlq = load_raw(DLQ_PATH)
    env_src = _module_preamble(needs_header=False)
    env_src += _model("EventEnvelopeHeader", env["fields"], with_header_import=False) + "\n\n"
    env_src += _model("DlqEnvelope", dlq["fields"], with_header_import=False)
    with open(os.path.join(out, "envelope.py"), "w") as f:
        f.write(env_src)

    exported = ["EventEnvelopeHeader", "DlqEnvelope"]

    for t in TOPICS:
        raw = load_raw(topic_schema_path(t))
        model_name = raw["name"]
        src = _module_preamble(needs_header=True)
        src += _model(model_name, raw["fields"], with_header_import=True)
        with open(os.path.join(out, f"{_snake(t)}.py"), "w") as f:
            f.write(src)
        exported.append(model_name)

    # __init__.py re-exports every model
    init = [HEADER, "from __future__ import annotations\n\n"]
    init.append("from .envelope import DlqEnvelope, EventEnvelopeHeader\n")
    for t in TOPICS:
        raw = load_raw(topic_schema_path(t))
        init.append(f"from .{_snake(t)} import {raw['name']}\n")
    init.append("\n__all__ = [\n")
    init.extend(f"    {name!r},\n" for name in exported)
    init.append("]\n")
    with open(os.path.join(out, "__init__.py"), "w") as f:
        f.write("".join(init))

    print(f"generated Python client: {len(TOPICS)} topic modules + envelope.py in {out}")


if __name__ == "__main__":
    main()
